#include"turk_sort.h"

int	main(void)
{
	size_t		col = 15;
	size_t		score;
	size_t		max_score = 6;
	size_t		i;
	bool		check;
	int			*dst;
	int			intarr[][15] = {
		{21,	34,	71,	59,	61,	41,	72,	80,	36,	13,	17,	79,	90,	73,	57},
		{64,	98,	12,	10,	73,	56,	39,	40,	53,	42,	95,	21,	31,	60,	19},
		{89,	78,	69,	42,	24,	59,	81,	96,	19,	87,	15,	80,	98,	63,	98},
		{74,	47,	70,	27,	96,	79,	20,	97,	93,	70,	93,	88,	20,	15,	78},
		{27,	85,	14,	88,	95,	33,	68,	68,	52,	39,	70,	83,	10,	12,	95},
		{44,	26,	10,	47,	54,	24,	12,	32,	57,	50,	19,	40,	15,	42,	96},
	};
	int			outarr[][15] = {
		{21,	34,	71,	59,	61,	41,	72,	80,	36,	13,	17,	79,	90,	73,	57},
		{98,	12,	10,	73,	56,	39,	40,	53,	42,	95,	21,	31,	60,	19,	64},
		{69,	42,	24,	59,	81,	96,	19,	87,	15,	80,	98,	63,	98,	89,	78},
		{27,	96,	79,	20,	97,	93,	70,	93,	88,	20,	15,	78,	74,	47,	70},
		{12,	95,	27,	85,	14,	88,	95,	33,	68,	68,	52,	39,	70,	83,	10},
		{96,	44,	26,	10,	47,	54,	24,	12,	32,	57,	50,	19,	40,	15,	42},
	};
	int			outarr1[][15] = {
		{34,	71,	59,	61,	41,	72,	80,	36,	13,	17,	79,	90,	73,	57,	57},
		{12,	10,	73,	56,	39,	40,	53,	42,	95,	21,	31,	60,	19,	64,	64},
		{42,	24,	59,	81,	96,	19,	87,	15,	80,	98,	63,	98,	89,	78,	78},
		{96,	79,	20,	97,	93,	70,	93,	88,	20,	15,	78,	74,	47,	70,	70},
		{95,	27,	85,	14,	88,	95,	33,	68,	68,	52,	39,	70,	83,	10,	10},
		{44,	26,	10,	47,	54,	24,	12,	32,	57,	50,	19,	40,	15,	42,	42},
	};

	score = 0;
	i = 0;
	while (i < max_score)
	{
		if (i > max_score / 2)
			dst = rotate_arr(intarr[i], col, (size_t)(max_score - i));
		else
			dst = rrotate_arr(intarr[i], col, i);
		if (is_2intarr_same(dst, outarr[i], col) == true)
			check = true;
		shift_by1_arr(dst, col);
		if (check == true && is_2intarr_same(outarr1[i], dst, col) == true)
			score += 1;
		write_intarr(dst, col);
		free(dst);
		i += 1;
	}
	write_total_score(score, max_score);
}

